#!/usr/bin/env node
// Builds src/survey/questions.generated.ts from survey-v2/Hobbi_Survey_Questions_v2.csv, so
// the research team's CSV stays the single source of truth for question wording.
// Run with: npm run survey:generate
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parseQuestionsCsv } from "./parse-questions.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const questions = parseQuestionsCsv(
  readFileSync(resolve(root, "survey-v2/Hobbi_Survey_Questions_v2.csv"), "utf8"),
);

const output = `// GENERATED by scripts/generate-questions.mjs from survey-v2/Hobbi_Survey_Questions_v2.csv.
// Do not edit by hand: change the CSV and run \`npm run survey:generate\`.
import type { Question } from "./types";

export const questions: readonly Question[] = ${JSON.stringify(questions, null, 2)};
`;

writeFileSync(resolve(root, "src/survey/questions.generated.ts"), output);
console.log(`Wrote ${questions.length} questions.`);
